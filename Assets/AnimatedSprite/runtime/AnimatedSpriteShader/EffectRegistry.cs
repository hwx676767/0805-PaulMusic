    public static class EffectRegistry
    {
        private static EffectParam F(string f, string s, string d, float mn, float mx, string def = null)
            => EffectParam.Float(f, s, d, mn, mx, def);
        private static EffectParam C(string f, string s, string d, string def = "Color.white")
            => EffectParam.Col(f, s, d, def);
        private static EffectParam H(string f, string s, string d, string def = "Color.white")
            => EffectParam.Hdr(f, s, d, def);
        private static EffectParam V2(string f, string s, string d, string def = "Vector2.zero")
            => EffectParam.Vec2(f, s, d, def);
        private static EffectParam V3(string f, string s, string d, string def = "Vector3.zero")
            => EffectParam.Vec3(f, s, d, def);
        private static EffectParam V(string f, string s, string d, string def = "Vector4.zero")
            => EffectParam.Vec(f, s, d, def);
        private static EffectParam T(string f, string s, string d)
            => EffectParam.Tex(f, s, d);
        private static EffectParam I(string f, string s, string d, int mn, int mx, int def = 0)
            => EffectParam.Int(f, s, d, mn, mx, def);

        private static EffectDef M(EffectId id, string name, string kw, string enable, string es, EffectCategory cat,
            string mf, string ms, params EffectParam[] p)
            => new EffectDef
            {
                id = id, name = name, keyword = kw, enableField = enable, enableShader = es,
                category = cat, group = CategoryToDefaultGroup(cat),
                hasMask = true, maskField = mf, maskShader = ms, parms = p, orderInGroup = 0
            };

        private static EffectDef MG(EffectId id, string name, string kw, string enable, string es, EffectCategory cat, EffectGroup grp,
            string mf, string ms, params EffectParam[] p)
            => new EffectDef
            {
                id = id, name = name, keyword = kw, enableField = enable, enableShader = es,
                category = cat, group = grp,
                hasMask = true, maskField = mf, maskShader = ms, parms = p, orderInGroup = 0
            };

        private static EffectGroup CategoryToDefaultGroup(EffectCategory cat)
        {
            return cat switch
            {
                EffectCategory.Color => EffectGroup.Color,
                EffectCategory.Edge => EffectGroup.Edge,
                EffectCategory.UV => EffectGroup.UV,
                EffectCategory.Dissolve => EffectGroup.Dissolve,
                EffectCategory.Special => EffectGroup.VFX,
                _ => EffectGroup.Game
            };
        }

